#!/usr/bin/env python3
"""Loop-closing Task 5.3 (correction 6): generate the UTS #39 confusable
prototype table that supabase/functions/_shared/confusables.ts uses, and the
ICU reference vectors its test checks.

    python3 scripts/loop-closing/gen-confusables.py

Source: the system ICU on macOS (/usr/lib/libicucore.dylib,
uspoof_getSkeleton), which implements UTS #39 skeleton() from the
confusables.txt data of its Unicode version. Nothing is downloaded. The
script refuses to run against any ICU other than PINNED_ICU, so the data is
pinned to one version; the written module records that version, its Unicode
version and the sha256 of the encoded table, and the test recomputes the
sha256.

The table keeps, for every code point that NFD and NFKC both leave as
itself, its prototype when that differs from the code point. The skeleton
code applies NFD first, removes default-ignorable code points (UTS #39 step
2), maps each code point through the table, and applies NFD again, so a
code point NFD or NFKC changes never reaches the table (identity text is
NFKC-normalised first), and default-ignorable code points need no entry.

Vectors: every table code point alone, a list of lookalike pairs, and 600
seeded random strings over Latin, Greek, Cyrillic, Armenian, Hebrew, Arabic,
CJK, Hangul and combining marks, each NFKC-normalised, with ICU's skeleton.
"""
import ctypes
import hashlib
import json
import os
import random
import sys
import unicodedata

PINNED_ICU = [78, 1, 0]
ROOT = os.path.abspath(os.path.join(os.path.dirname(__file__), "..", ".."))
OUT_TS = os.path.join(ROOT, "supabase/functions/_shared/confusables-data.ts")
OUT_VECTORS = os.path.join(ROOT, "scripts/loop-closing/confusables-vectors.json")

lib = ctypes.CDLL("/usr/lib/libicucore.dylib")
ver = (ctypes.c_uint8 * 4)()
lib.u_getVersion(ver)
uver = (ctypes.c_uint8 * 4)()
lib.u_getUnicodeVersion(uver)
icu, uni = list(ver)[:3], list(uver)[:3]
if icu != PINNED_ICU:
    print(f"refusing: system ICU is {icu}, the pinned version is {PINNED_ICU}", file=sys.stderr)
    sys.exit(2)
err = ctypes.c_int(0)
lib.uspoof_open.restype = ctypes.c_void_p
checker = lib.uspoof_open(ctypes.byref(err))
if err.value > 0:
    print(f"uspoof_open failed: {err.value}", file=sys.stderr)
    sys.exit(2)
lib.uspoof_getSkeleton.argtypes = [ctypes.c_void_p, ctypes.c_uint32, ctypes.c_void_p, ctypes.c_int32,
                                   ctypes.c_void_p, ctypes.c_int32, ctypes.POINTER(ctypes.c_int)]


def skeleton(s: str) -> str:
    b = s.encode("utf-16-le")
    n = len(b) // 2
    src = (ctypes.c_uint16 * max(n, 1)).from_buffer_copy(b if n else b"\0\0")
    out = (ctypes.c_uint16 * 4096)()
    e = ctypes.c_int(0)
    k = lib.uspoof_getSkeleton(ctypes.c_void_p(checker), 0, src, n, out, 4096, ctypes.byref(e))
    if e.value > 0:
        raise RuntimeError(f"uspoof_getSkeleton failed on {s!r}: {e.value}")
    return bytes(out)[: k * 2].decode("utf-16-le")


table = {}
for cp in range(0x110000):
    if 0xD800 <= cp <= 0xDFFF:
        continue
    c = chr(cp)
    if unicodedata.normalize("NFD", c) != c or unicodedata.normalize("NFKC", c) != c:
        continue
    k = skeleton(c)
    if k and k != c:
        table[cp] = k
encoded = ";".join(format(cp, "x") + ":" + " ".join(format(ord(x), "x") for x in v) for cp, v in sorted(table.items()))
digest = hashlib.sha256(encoded.encode("ascii")).hexdigest()

with open(OUT_TS, "w", encoding="ascii") as f:
    f.write("// GENERATED by scripts/loop-closing/gen-confusables.py; do not edit.\n")
    f.write(f"// UTS #39 confusable prototypes from ICU {'.'.join(map(str, icu))} (Unicode {'.'.join(map(str, uni))}),\n")
    f.write("// read from the system ICU's uspoof_getSkeleton, one code point at a time.\n")
    f.write("// Entries: hex code point, ':', the prototype's code points in hex; ';' between entries.\n")
    f.write(f"export const CONFUSABLES_SOURCE = \"ICU {'.'.join(map(str, icu))}, Unicode {'.'.join(map(str, uni))}\";\n")
    f.write(f"export const CONFUSABLES_SHA256 = \"{digest}\";\n")
    f.write(f"export const CONFUSABLES_COUNT = {len(table)};\n")
    f.write("export const CONFUSABLES =\n")
    for i in range(0, len(encoded), 100):
        f.write(f"  \"{encoded[i:i + 100]}\"" + (" +\n" if i + 100 < len(encoded) else ";\n"))

rng = random.Random(20261121)
pools = [range(0x41, 0x5B), range(0x61, 0x7B), range(0xC0, 0x250), range(0x370, 0x400), range(0x400, 0x530),
         range(0x531, 0x590), range(0x5D0, 0x5EB), range(0x620, 0x64B), range(0x4E00, 0x4E80), range(0xAC00, 0xAD00),
         range(0x300, 0x370), range(0x1D00, 0x1DC0)]
chars = [chr(cp) for pool in pools for cp in pool if unicodedata.category(chr(cp)) != "Cn"]
inputs = [chr(cp) for cp in sorted(table)]
inputs += ["José Li", "José Li", "Alicia Brennan", "Аlicia Brennan", "Bjørn Li", "Bjo̸rn Li",
           "Ιan Lee", "Ian Lee", "lan Lee", "Kim Lee", "Kirn Lee", "Paige Smith", "Рaige Smith",
           "Zoë Brontë", "Ζoë Brontë", "οlga", "olga", "ɡeorge", "george"]
for _ in range(600):
    inputs.append("".join(rng.choice(chars) for _ in range(rng.randint(1, 8))))
vectors = []
for s in inputs:
    t = unicodedata.normalize("NFKC", s)
    vectors.append([t, skeleton(t)])
with open(OUT_VECTORS, "w", encoding="utf-8") as f:
    json.dump({"source": f"ICU {'.'.join(map(str, icu))}, Unicode {'.'.join(map(str, uni))}", "vectors": vectors}, f, ensure_ascii=True, indent=0)
print(f"{len(table)} prototypes, sha256 {digest}, {len(vectors)} vectors")
