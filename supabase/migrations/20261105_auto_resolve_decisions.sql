--           drop function public.auto_resolve_decision_payload_ok(text, text, text, uuid, uuid, uuid, uuid, uuid, text, numeric);

-- The legal triples. Null-safe on reason, and exists() returns false (never
-- SQL null) for a triple outside the mapping, so the CHECK refuses it.
create or replace function public.auto_resolve_decision_legal(
  p_layer text, p_outcome text, p_reason text
) returns boolean
language sql immutable
set search_path = pg_catalog, public
as $$
  select exists (
    select 1 from (values
      ('L0', 'blocked', 'mechanical_prefix'),
      ('L0', 'blocked', 'operation_command'),
      ('L1.5', 'dropped', 'restatement'),
      ('L2', 'dropped', 'not_claimed'),
      ('L2', 'dropped', 'llm_failed'),
      ('L2', 'dropped', 'parse_failed'),
      ('L3', 'dropped', 'no_quote'),
      ('L3', 'dropped', 'coverage_below_threshold'),
      ('L3.5', 'vetoed', 'still_owed'),
      ('resolved', 'resolved', null::text),
      ('gate', 'dropped', 'work_report'),
      ('archive', 'proposed', 'age_work_report'),
      ('archive', 'proposed', 'age_standard'),
      ('archive', 'proposed', 'deadline_passed'),
      ('archive', 'kept', 'age_work_report'),
      ('archive', 'kept', 'age_standard'),
      ('archive', 'kept', 'deadline_passed'),
      ('archive', 'accepted', 'age_work_report'),
      ('archive', 'accepted', 'age_standard'),
      ('archive', 'accepted', 'deadline_passed'),
      ('recheck', 'proposed', null::text),
      ('recheck', 'kept', null::text),
      ('recheck', 'accepted', null::text),
      ('recheck', 'no_evidence', 'none_found'),
      ('recheck', 'no_evidence', 'thought_not_in_page'),
      ('recheck', 'no_evidence', 'quote_not_verbatim'),
      ('recheck', 'no_evidence', 'veto'),
      ('recheck', 'no_evidence', 'coverage'),
      ('recheck', 'no_evidence', 'scope_mismatch'),
      ('fragment', 'dropped', 'one_token'),
      ('fragment', 'dropped', 'dangling_clause'),
      ('fragment', 'proposed', 'pronoun_object'),
      ('fragment', 'kept', 'pronoun_object'),
      ('fragment', 'accepted', 'pronoun_object'),
